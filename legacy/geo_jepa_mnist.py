"""
Geo-JEPA Prototype: MCR² Encoder + Gene Interaction Prior + JEPA Training
==========================================================================
Target hardware: MacBook Air (Apple Silicon, 16-32GB)
Framework:       PyTorch 2.x with MPS backend

Architecture summary:
  Stage 1 - Gene Interaction Prior:  Single sparse attention layer over
                                      expressed "genes" (MNIST pixels)
  Stage 2 - MCR² ReduNet:             L unrolled gradient steps on the
                                      Maximal Coding Rate Reduction objective
  JEPA Loop:  EMA target encoder + predictor MLP trained to predict
              target gene-set embeddings from context gene-set embeddings

Dataset: MNIST proxy with MNAR dropout and fate bifurcation structure
         (generated by build_proxy_dataset.py, loaded from data/)

Usage:
  python build_proxy_dataset.py                    # generate dataset first
  python geo_jepa_mnist.py                         # train with defaults
  python geo_jepa_mnist.py --phase_a_epochs 10     # shorter Phase A
"""

