"""
Geo-JEPA Simple: MLP Encoder + MCR² Loss + JEPA Training
==========================================================
Two-phase training on MNIST proxy dataset simulating scRNA-seq.

Phase A — Room Separation (homeostatic cells):
  MLP encoder (2000D → 512 → 512 → 128, L2-normalized) learns orthogonal
  subspaces per cell type via MCR² loss (d×d eigvalsh, MPS-native).
  JEPA gene-set masking + EMA target encoder for self-supervised structure.
  Result: DR ~1.9-2.3x, off-diagonal cosine ~0.02, clean UMAP separation.

Phase B — Trajectory Prediction (perturbation cells):
  Frozen encoder + TrajectoryPredictor MLP learns to map
  (z_source + perturbation_embedding) → z_destination via residual displacement.
  Cosine similarity loss on the unit sphere.
  Result: Predicted DR ~1.25-1.37x (actual DR ~1.9-2.3x). Predictions land in
  the correct neighborhood but lack precision — likely needs encoder fine-tuning
  or richer perturbation representations. See GEO_JEPA_PLAN.md for next steps.

Output: results/training/ (metrics.jsonl, PNGs, Phase A checkpoint)
Dataset: MNIST proxy (generated by build_proxy_dataset.py)
"""

