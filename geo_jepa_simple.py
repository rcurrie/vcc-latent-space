def build_perturbation_training_data(data):
    """Build paired (source_cell, perturbed_cell) from already-loaded data.

    Uses data["pert_*"] arrays from load_proxy_dataset().
    Skips pert 3 (partial priming) — no single destination.
    Pairs each perturbed cell with a random homeostatic cell from its source room.
    """
    pert_cells = data["pert_cells"]
    pert_labels = data["pert_labels"]  # source room label per cell
    pert_ids = data["pert_ids"]
    pert_str = data["pert_strengths"]

    # Only use perturbations with deterministic destinations (skip pert 3)
    use_mask = np.isin(pert_ids, [0, 1, 2, 4])
    pert_cells = pert_cells[use_mask]
    pert_labels = pert_labels[use_mask]
    pert_ids = pert_ids[use_mask]
    pert_str = pert_str[use_mask]

    # For each perturbed cell, sample a random source cell from its source room
    homeostatic = data["homeostatic"]
    class_labels = data["class_labels"]
    rng = np.random.default_rng(42)
    source_cells = np.zeros_like(pert_cells)
    for src_label in np.unique(pert_labels):
        mask = pert_labels == src_label
        room_cells = homeostatic[class_labels == src_label]
        chosen = rng.integers(0, len(room_cells), size=mask.sum())
        source_cells[mask] = room_cells[chosen]

    print(f"Phase B data: {len(pert_cells)} perturbation pairs "
          f"(pert types: {sorted(set(pert_ids))})")
    return PerturbationDataset(source_cells, pert_cells, pert_ids, pert_str)

# %% [4] MCR² Loss (d×d formulation — stable on MPS, no Cholesky)
def coding_rate(Z: torch.Tensor, eps: float = 0.5) -> torch.Tensor:
    """
    R(Z, eps) = (d/2) log det(I + d/(n*eps^2) Z^T Z)
    Uses eigvalsh on (d×d) matrix — works on MPS without fallback.
    """
    n, d = Z.shape
    alpha = d / (n * eps ** 2)
    M = torch.eye(d, device=Z.device) + alpha * (Z.T @ Z)
    if M.device.type == "mps":
        eigvals = torch.linalg.eigvalsh(M.cpu()).to(Z.device)
    else:
        eigvals = torch.linalg.eigvalsh(M)
    return 0.5 * torch.sum(torch.log(eigvals.clamp(min=1e-7)))


def mcr2_loss(Z, labels, n_classes, eps=0.5):
    """MCR² with hard labels. Returns (loss, R_total, R_compress, delta_R)."""
    R_total = coding_rate(Z, eps)
    R_compress = torch.tensor(0.0, device=Z.device)
    n = Z.shape[0]
    for k in range(n_classes):
        mask = labels == k
        n_k = mask.sum()
        if n_k < 2:
            continue
        R_compress = R_compress + (n_k / n) * coding_rate(Z[mask], eps)

    delta_R = R_total - R_compress
    return -delta_R, R_total.item(), R_compress.item(), delta_R.item()

# %% [5] Models
class MLPEncoder(nn.Module):
    """MLP encoder: gene_dim -> hidden -> embed_dim, L2 normalized.
    Placeholder for future attention + ReduNet."""
    def __init__(self, gene_dim, embed_dim, hidden_dim=512):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(gene_dim, hidden_dim),
            nn.BatchNorm1d(hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, hidden_dim),
            nn.BatchNorm1d(hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, embed_dim),
        )

    def forward(self, x):
        return F.normalize(self.net(x), dim=1)


class Predictor(nn.Module):
    """MLP predictor: z_context -> z_target_hat."""
    def __init__(self, embed_dim, hidden_dim=256):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(embed_dim, hidden_dim),
            nn.GELU(),
            nn.LayerNorm(hidden_dim),
            nn.Linear(hidden_dim, hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, embed_dim),
        )

    def forward(self, z):
        return F.normalize(self.net(z), dim=1)


class TrajectoryPredictor(nn.Module):
    """Predicts destination via residual displacement from source embedding.

    Instead of predicting absolute z_dest, predicts a delta:
        z_dest = normalize(z_source + delta(z_source, pert, dose))

    This gives the predictor a strong prior: "start where you are, shift
    toward the destination." The MLP only needs to learn the displacement,
    which is much easier than learning absolute positions.
    """
    def __init__(self, embed_dim, n_pert_types=5, pert_embed_dim=32, hidden_dim=256):
        super().__init__()
        self.pert_embed = nn.Embedding(n_pert_types, pert_embed_dim)
        self.net = nn.Sequential(
            nn.Linear(embed_dim + pert_embed_dim, hidden_dim),
            nn.GELU(),
            nn.LayerNorm(hidden_dim),
            nn.Linear(hidden_dim, hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, embed_dim),
        )

    def forward(self, z_source, pert_id, dose):
        """
        z_source: (B, embed_dim) — encoded source cell
        pert_id:  (B,) int — perturbation type (0-4)
        dose:     (B,) float — strength 0.3/0.6/1.0
        """
        pe = self.pert_embed(pert_id) * dose.unsqueeze(1)
        h = torch.cat([z_source, pe], dim=1)
        delta = self.net(h)
        return F.normalize(z_source + delta, dim=1)


def gene_set_mask(x, context_ratio=0.75):
    """Partition genes into context (visible) and target (masked)."""
    gene_dim = x.shape[1]
    n_context = int(gene_dim * context_ratio)
    perm = torch.randperm(gene_dim, device=x.device)
    x_context = torch.zeros_like(x)
    x_context[:, perm[:n_context]] = x[:, perm[:n_context]]
    x_target = torch.zeros_like(x)
    x_target[:, perm[n_context:]] = x[:, perm[n_context:]]
    return x_context, x_target


@torch.no_grad()
def ema_update(online, target, momentum=0.996):
    for p_o, p_t in zip(online.parameters(), target.parameters()):
        p_t.data.mul_(momentum).add_(p_o.data, alpha=1.0 - momentum)


