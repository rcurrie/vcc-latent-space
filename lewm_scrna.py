"""
LeWM-scRNA: World Model for Single-Cell Perturbation Prediction
================================================================
Inspired by LeWorldModel (le-wm.github.io), treats perturbations as "actions"
in a latent world model. Uses SIGReg (Sketched-Isotropic-Gaussian Regularizer)
instead of MCR² for unsupervised collapse prevention.

Phase 1 — Homeostatic Structure (this file):
  MLP encoder with BatchNorm projector (no L2 norm) + JEPA gene-set masking.
  SIGReg enforces isotropic Gaussian embeddings via Epps-Pulley test on
  random 1D projections (Cramér-Wold theorem). No EMA target encoder needed.

Future — Perturbation Prediction:
  AdaLN-conditioned predictor maps (z_cell, a_perturbation) -> z_post.
  Perturbations = actions in the world model.

Dataset: MNIST proxy (generated by build_proxy_dataset.py)
Output: results/lewm/
"""

